    private static CatalogDownloadSource Direct(string id, string name, string manufacturer, string code,
        string page, string download, string? terms, string notice, bool bundle = false, string[]? hosts = null) =>
        new(id, name, code, new(page), new(download), Array.AsReadOnly(hosts ?? [new Uri(download).IdnHost]),
            bundle ? CatalogSourceAvailability.Bundle : CatalogSourceAvailability.Direct, CatalogSourceRights.Unknown,
            terms is null ? null : new(terms), "source-policy-2026-10-28-v1:" + id,
            notice + " Public access does not establish permission for use in BusChord.", "knxprod / ZIP", Verified, manufacturer);

