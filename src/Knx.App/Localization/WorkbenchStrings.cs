{
    public WbExtension() { }

    public WbExtension(string key) => Key = key;

    [ConstructorArgument("key")]
    public string Key { get; set; } = "";

    public override object ProvideValue(IServiceProvider serviceProvider) => WorkbenchStrings.Get(Key);
}
