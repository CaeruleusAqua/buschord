/// <summary>XAML counterpart of <see cref="WorkbenchStrings"/>: {loc:Wb Key}.</summary>
public sealed class WbExtension : MarkupExtension
{
    public WbExtension() { }

    public WbExtension(string key) => Key = key;

    [ConstructorArgument("key")]
    public string Key { get; set; } = "";

    public override object ProvideValue(IServiceProvider serviceProvider) =>
        new Binding($"[{Key}]") { Source = WorkbenchStrings.Instance, Mode = BindingMode.OneWay };
}
